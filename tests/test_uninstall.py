from __future__ import annotations

import json
from pathlib import Path
from typing import TYPE_CHECKING
from unittest.mock import patch

import pytest

from cline_hooks._main import main
from cline_hooks.uninstall import CLINE_HOOK_NAMES, uninstall_cline, uninstall_copilot

if TYPE_CHECKING:
    from collections.abc import Iterator

_BINARY = "/opt/env/bin/cline-hook"


@pytest.fixture
def copilot_file(tmp_path: Path) -> Iterator[Path]:
    with patch.object(Path, "home", return_value=tmp_path):
        yield tmp_path / ".copilot" / "hooks" / "cline-hooks.json"


def _write(path: Path, config: dict[str, object]) -> None:
    path.parent.mkdir(parents=True)
    path.write_text(json.dumps(config), encoding="utf-8")


class TestUninstallCline:
    def test_removes_cline_hook_symlinks_and_generated_scripts(self, tmp_path: Path) -> None:
        (tmp_path / CLINE_HOOK_NAMES[0]).symlink_to(_BINARY)
        script = tmp_path / f"{CLINE_HOOK_NAMES[1]}.ps1"
        script.write_text("# Generated by cline-hook install.\n$inputData | & 'x'\n", encoding="utf-8")

        uninstall_cline(str(tmp_path))

        assert list(tmp_path.iterdir()) == []

    def test_leaves_hooks_cline_hooks_did_not_write(self, tmp_path: Path) -> None:
        own_file = tmp_path / CLINE_HOOK_NAMES[0]
        own_file.write_text("custom", encoding="utf-8")
        other_link = tmp_path / CLINE_HOOK_NAMES[1]
        other_link.symlink_to("/usr/bin/true")
        custom_script = tmp_path / f"{CLINE_HOOK_NAMES[2]}.ps1"
        custom_script.write_text("Write-Host 'custom'\n", encoding="utf-8")

        uninstall_cline(str(tmp_path))

        assert own_file.exists()
        assert other_link.is_symlink()
        assert custom_script.exists()


class TestUninstallCopilot:
    def test_removes_the_hook_file_through_the_cli(self, copilot_file: Path) -> None:
        _write(copilot_file, {"hooks": {"Stop": [{"type": "command", "command": _BINARY}]}})

        with patch("sys.argv", ["cline-hook", "uninstall", "copilot"]), pytest.raises(SystemExit) as excinfo:
            main()

        assert excinfo.value.code == 0
        assert not copilot_file.exists()

    def test_keeps_entries_cline_hooks_did_not_write(self, copilot_file: Path) -> None:
        other = {"type": "command", "command": "/usr/bin/other"}
        _write(
            copilot_file,
            {
                "version": 1,
                "hooks": {
                    "PreToolUse": [{"type": "command", "command": _BINARY}, other],
                    "Stop": [{"type": "command", "command": _BINARY}],
                },
            },
        )

        uninstall_copilot()

        assert json.loads(copilot_file.read_text(encoding="utf-8")) == {"version": 1, "hooks": {"PreToolUse": [other]}}
