"""Removal of the hooks older versions installed for Cline and GitHub Copilot."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from cline_hooks.core.install import binary_names

CLINE_HOOK_NAMES = (
    "PreToolUse",
    "PostToolUse",
    "TaskStart",
    "TaskResume",
    "TaskCancel",
    "TaskComplete",
    "UserPromptSubmit",
    "PreCompact",
    "Stop",
)
_PS1_HEADER = "# Generated by cline-hook install."


def uninstall_cline(target: str) -> None:
    """Remove the cline-hook symlinks and generated PowerShell scripts from Cline's hooks directory.

    Args:
        target: The directory `cline-hook install cline` was given.
    """
    target_dir = Path(target)
    removed = 0
    for hook in CLINE_HOOK_NAMES:
        link = target_dir / hook
        script = target_dir / f"{hook}.ps1"
        if link.is_symlink() and Path(str(link.readlink())).name in binary_names():
            link.unlink()
        elif script.is_file() and script.read_text(encoding="utf-8").startswith(_PS1_HEADER):
            script.unlink()
        else:
            continue
        removed += 1
    print(f"{removed} hooks removed.")


def uninstall_copilot() -> None:
    """Remove the cline-hook entries from ~/.copilot/hooks/cline-hooks.json, deleting the file once empty."""
    config_path = Path.home() / ".copilot" / "hooks" / "cline-hooks.json"
    if not config_path.exists():
        print(f"{config_path} does not exist.")
        return
    config: dict[str, Any] = json.loads(config_path.read_text(encoding="utf-8"))
    events: dict[str, list[dict[str, str]]] = config.get("hooks", {})
    kept = {
        event: remaining
        for event, entries in events.items()
        if (remaining := [e for e in entries if Path(e.get("command", "")).name not in binary_names()])
    }
    if kept:
        config["hooks"] = kept
        config_path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
        print(f"Removed the cline-hook entries from {config_path}.")
    else:
        config_path.unlink()
        print(f"Removed {config_path}.")
