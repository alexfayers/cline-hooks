from __future__ import annotations

import re
from typing import TYPE_CHECKING

from cline_hooks.core.plugin import collect_hook_results, load_plugins
from cline_hooks.core.registry import hook_handler
from cline_hooks.core.response import allow
from cline_hooks.core.timing import TIME_FORMAT, local_now
from cline_hooks.core.vocabulary import CanonicalHook

if TYPE_CHECKING:
    from cline_hooks.core.models import HookInputUserPromptSubmit

_AGENT_MESSAGE_PATTERN = re.compile(
    r"<(agent-message|teammate-message|task-notification|cross-session-message).+?</\1>", re.DOTALL
)
_PEER_MESSAGE_PATTERN = re.compile(r"<cross-session-message.+?</cross-session-message>", re.DOTALL)


def _is_agent_message(message: str) -> bool:
    """Check if a message was generated by another agent rather than typed by the user.

    Returns:
        True if the message contains an agent-message, teammate-message,
        task-notification or cross-session-message wrapper element.
    """
    return bool(_AGENT_MESSAGE_PATTERN.search(message))


def _is_peer_message(message: str) -> bool:
    """Check if a message contains a cross-session peer message wrapper element.

    Returns:
        True if the message contains a cross-session-message element.
    """
    return bool(_PEER_MESSAGE_PATTERN.search(message))


@hook_handler(CanonicalHook.USER_PROMPT_SUBMIT)
def handle_user_prompt_submit(hook: HookInputUserPromptSubmit) -> None:
    """Handle UserPromptSubmit hook events.

    Agent-generated messages skip the TIME note and every plugin, except that
    cross-session peer messages still reach plugins with `handles_peer_messages`.

    Args:
        hook: The hook input data.
    """
    message = hook.userPromptSubmit.userMessage if hook.userPromptSubmit else ""
    if not message:
        return
    is_peer = _is_peer_message(message)
    if _is_agent_message(message) and not is_peer:
        return

    plugins = [plugin for plugin in load_plugins() if plugin.handles_peer_messages] if is_peer else load_plugins()
    notes: list[str] = [] if is_peer else [f"TIME: {local_now().strftime(TIME_FORMAT)}."]

    result = collect_hook_results(
        plugins,
        "UserPromptSubmit",
        message=message,
        task_id=hook.stateKey,
        workspace_roots=hook.workspaceRoots,
        agent_type=hook.agentType,
        transcript_path=hook.transcriptPath,
        agent_id=hook.agentId,
        is_teammate=hook.isTeammate,
    )
    notes.extend(result.notes)

    if notes:
        allow("\n\n".join(notes), prefix="")
